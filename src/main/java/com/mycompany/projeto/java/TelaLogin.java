    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        String cpf = txtCpfLogin.getText().trim();
        String senha = new String(txtSenhaLogin.getPassword());

        if (cpf.isEmpty() || senha.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Informe seu CPF e sua senha.");
            return;
}

        try {
            InvestidorDAO dao = new InvestidorDAO();
            Investidor investidor = dao.consultarPorCpf(cpf);

            if (investidor == null) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "CPF não cadastrado. Faça seu cadastro primeiro.");
             return;
    }

        if (!investidor.validarSenha(senha)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                 "Senha incorreta.");
            return;
    }
        

        javax.swing.JOptionPane.showMessageDialog(this,
                "Bem-vindo, " + investidor.getNome() + "!");
        dao.criarCarteira(cpf);
        investidor.setCarteira(dao.carregarCarteira(cpf));
        for (Operacao operacao : dao.carregarOperacoes(cpf)) {
            investidor.getCarteira().registrarOperacao(operacao);
}

        new TelaPrincipal1(investidor).setVisible(true);
        this.dispose();

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Erro ao acessar o banco de dados: " + e.getMessage());
}
    }//GEN-LAST:event_btnEntrarActionPerformed

