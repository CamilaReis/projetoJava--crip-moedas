//ATUALIZACO COTAÇAO botton 6
    private void jButton6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton6ActionPerformed
    
    double cotacaoBitcoin = bitcoin.getCotacao();
    double cotacaoEthereum = ethereum.getCotacao();
    double cotacaoRipple = ripple.getCotacao();

    double variacaoBitcoin = (Math.random() * 0.10) - 0.05;
    double variacaoEthereum = (Math.random() * 0.10) - 0.05;
    double variacaoRipple = (Math.random() * 0.10) - 0.05;

    cotacaoBitcoin = cotacaoBitcoin * (1 + variacaoBitcoin);
    cotacaoEthereum = cotacaoEthereum * (1 + variacaoEthereum);
    cotacaoRipple = cotacaoRipple * (1 + variacaoRipple);

    bitcoin.setCotacao(cotacaoBitcoin);
    ethereum.setCotacao(cotacaoEthereum);
    ripple.setCotacao(cotacaoRipple);

    javax.swing.JOptionPane.showMessageDialog(this,
        "Novas cotações:\n"
        + "Bitcoin: R$ " + bitcoin.getCotacao()
        + "\nEthereum: R$ " + ethereum.getCotacao()
        + "\nRipple: R$ " + ripple.getCotacao());


    }//GEN-LAST:event_jButton6ActionPerformed
