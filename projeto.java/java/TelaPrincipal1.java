//COMPRAR CRIPTOMOEDAS jbotton 4 
    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    String[] moedas = {"Bitcoin", "Ethereum", "Ripple"};
    String escolha = (String) javax.swing.JOptionPane.showInputDialog(
        this,
        "Escolha a criptomoeda:",
        "Comprar criptomoedas",
        javax.swing.JOptionPane.QUESTION_MESSAGE,
        null,
        moedas,
        moedas[0]
);

if (escolha == null) {
    return;
}

Moedas moeda;

if (escolha.equals("Bitcoin")) {
    moeda = bitcoin;
} else if (escolha.equals("Ethereum")) {
    moeda = ethereum;
} else {
    moeda = ripple;
}

String entrada = javax.swing.JOptionPane.showInputDialog(
    this, "Digite o valor em reais que deseja usar na compra:"
);

if (entrada == null) {
    return;
}

try {
    double valor = Double.parseDouble(entrada.replace(",", "."));

    double taxa = 0.01;

    if (moeda.getSigla().equals("BTC")) {
        taxa = 0.02;
    }

    carteira.comprar(moeda, valor, taxa);

double taxaValor = valor * taxa;
double quantidade = (valor - taxaValor) / moeda.getCotacao();

    javax.swing.JOptionPane.showMessageDialog(this,
        "Compra realizada!\nMoeda: " + moeda.getNome()
        + "\nCotação: R$ " + moeda.getCotacao()
        + "\nValor utilizado: R$ " + valor
        + "\nTaxa: R$ " + taxaValor
        + "\nQuantidade comprada: " + quantidade);

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Digite um valor numérico válido.");
} catch (IllegalArgumentException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        e.getMessage());
}
    }//GEN-LAST:event_jButton4ActionPerformed
